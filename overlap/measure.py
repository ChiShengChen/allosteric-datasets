#!/usr/bin/env python
"""Which sets share structures, and which share proteins.

Two sets that overlap are not two experiments. This is the number that decides whether
"we validated on a second set" means anything, and it is the one thing none of the three
source repositories states about the others, because none of them was looking at all
three at once.

It matters most for the obvious next experiment: train on the large set, test on the
small curated one. If those two share most of their structures, that experiment is
contaminated and its result will look like a clean generalisation.

Writes `overlap/README.md`. Run it after any builder changes what is in `sets/`.
"""
from __future__ import annotations

import glob
import itertools
import os
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SETS = os.path.join(os.path.dirname(HERE), "sets")


def survey():
    out = {}
    for d in sorted(glob.glob(os.path.join(SETS, "*"))):
        if not os.path.isdir(d):
            continue
        pdbs, unis, rules, conf = set(), set(), set(), set()
        files = sorted(glob.glob(os.path.join(d, "*.npz")))
        for f in files:
            z = np.load(f, allow_pickle=True)
            p = str(z["pdb"]).upper() if "pdb" in z.files else ""
            if p:
                pdbs.add(p)
            if "uniprot" in z.files and str(z["uniprot"]):
                unis.add(str(z["uniprot"]))
            rules.add(str(z["label_rule"]))
            conf.add(str(z["conformation"]))
        out[os.path.basename(d)] = dict(n=len(files), pdbs=pdbs, unis=unis,
                                        rules=sorted(rules), conf=sorted(conf))
    return out


def main():
    s = survey()
    if not s:
        print(f"no sets under {SETS}")
        return

    lines = ["# Overlap between the sets", "",
             "Generated by `overlap/measure.py`. Two sets that share structures are not "
             "two independent experiments, and the sets here were built by three "
             "different projects that were not comparing notes.", "",
             "## What is here", "",
             "| set | targets | distinct PDB | distinct UniProt | label rule | conformation |",
             "|---|---|---|---|---|---|"]
    for name, v in s.items():
        lines.append(f"| `{name}` | {v['n']} | {len(v['pdbs'])} | "
                     f"{len(v['unis']) if v['unis'] else '—'} | "
                     f"{', '.join(v['rules'])} | {', '.join(v['conf'])} |")

    lines += ["", "## Shared structures, by PDB id", "",
              "Read the percentage against the **smaller** set: that is the one whose "
              "independence is destroyed.", "",
              "| set A | set B | shared PDB | % of A | % of B |", "|---|---|---|---|---|"]
    worst = []
    for a, b in itertools.combinations(s, 2):
        pa, pb = s[a]["pdbs"], s[b]["pdbs"]
        if not pa or not pb:
            continue
        sh = pa & pb
        if not sh:
            continue
        fa, fb = len(sh) / len(pa), len(sh) / len(pb)
        lines.append(f"| `{a}` | `{b}` | {len(sh)} | {fa:.0%} | {fb:.0%} |")
        if max(fa, fb) >= 0.25:
            worst.append((a, b, len(sh), fa, fb))

    if worst:
        lines += ["", "## The ones that matter", ""]
        for a, b, n, fa, fb in sorted(worst, key=lambda t: -max(t[3], t[4])):
            small, frac = (a, fa) if fa > fb else (b, fb)
            lines.append(
                f"- **`{a}` and `{b}` share {n} structures — {frac:.0%} of `{small}`.** "
                f"Training on one and testing on the other is contaminated at that rate. "
                f"They may still be reported side by side, because the label rules "
                f"differ and the sets are never pooled, but neither is a held-out "
                f"replication of the other.")

    # A protein can be shared even when no structure is.
    lines += ["", "## Shared proteins, by UniProt accession", "",
              "Weaker than a shared structure and still enough to break a grouped split.",
              "", "| set A | set B | shared UniProt |", "|---|---|---|"]
    any_uni = False
    for a, b in itertools.combinations(s, 2):
        ua, ub = s[a]["unis"], s[b]["unis"]
        if ua and ub and (ua & ub):
            lines.append(f"| `{a}` | `{b}` | {len(ua & ub)} |")
            any_uni = True
    if not any_uni:
        lines.append("| — | — | no set pair carries UniProt on both sides |")

    lines += ["", "## What is not measured here", "",
              "Sequence identity. Two different proteins at 90% identity are two "
              "different accessions and two different PDB ids, and this file will call "
              "them disjoint. A homology-aware version needs an aligner this repository "
              "does not depend on; until then, treat every number above as a **lower "
              "bound** on how much the sets share.", ""]

    p = os.path.join(HERE, "README.md")
    open(p, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[:8]))
    print(f"\nwrote {p}")


if __name__ == "__main__":
    main()
